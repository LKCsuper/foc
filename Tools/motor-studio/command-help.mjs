export function describeCommand(line){
  const normalized=line.trim().replace(/\s+/g,' ');
  const exact=Object.keys(actionHelp).filter(key=>normalized===key||normalized.startsWith(key+' ')).sort((a,b)=>b.length-a.length)[0];
  return exact? actionHelp[exact]:commandHelp[normalized.split(' ')[0]];
}
